import { test, expect } from "@playwright/test";

test("profil: edycja, usuwanie pozycji, czyszczenie i aktualne powitanie", async ({ page, context }) => {
  expect((await context.request.get("/profile", { maxRedirects: 0 })).status()).toBe(307);
  for (const method of ["GET", "PATCH", "DELETE"]) {
    expect((await context.request.fetch("/api/profile", { method })).status()).toBe(401);
  }
  await page.goto("/?new=1");
  await expect(page.getByRole("button", { name: "Nowa rozmowa", exact: true })).toBeEnabled();
  await context.request.delete("/api/profile");
  await page.reload();
  await expect(page.getByRole("heading", { name: "Cześć!", exact: true })).toBeVisible();
  await expect(page.getByText("Jak mam się do Ciebie zwracać?", { exact: true })).toBeVisible();
  await page.getByRole("link", { name: "Profil", exact: true }).click();
  await page.getByRole("textbox", { name: "Imię", exact: true }).fill("Ola");
  await page.getByRole("button", { name: "Zapisz: Imię", exact: true }).click();
  await expect(page.getByRole("status")).toHaveText("Zapisano zmianę.");
  await page.goto("/?new=1");
  await expect(page.getByRole("heading", { name: "Cześć, Ola!", exact: true })).toBeVisible();
  await page.getByLabel("Wiadomość klienta", { exact: true }).fill("Lubię pierogi.");
  await page.getByRole("button", { name: "Wyślij", exact: true }).click();
  await expect(page.locator(".message.assistant").last()).toContainText("Zapamiętałem: ulubione jedzenie — pierogi.");
  await expect(page.getByRole("button", { name: "Nowa rozmowa", exact: true })).toBeEnabled();
  await page.getByRole("link", { name: "Profil", exact: true }).click();
  await expect(page.getByRole("textbox", { name: "Ulubione jedzenie", exact: true })).toHaveValue("pierogi");
  await page.getByRole("textbox", { name: "Imię", exact: true }).fill("Alicja");
  await page.getByRole("button", { name: "Zapisz: Imię", exact: true }).click();
  await expect(page.getByRole("status")).toHaveText("Zapisano zmianę.");
  await page.reload();
  await expect(page.getByRole("textbox", { name: "Imię", exact: true })).toHaveValue("Alicja");
  await expect(page.getByRole("textbox", { name: "Ulubione jedzenie", exact: true })).toHaveValue("pierogi");
  await page.getByRole("textbox", { name: "Ulubione jedzenie", exact: true }).fill("makaron");
  await page.getByRole("button", { name: "Zapisz: Ulubione jedzenie", exact: true }).click();
  await expect(page.getByRole("status")).toHaveText("Zapisano zmianę.");
  await page.reload();
  await expect(page.getByRole("textbox", { name: "Ulubione jedzenie", exact: true })).toHaveValue("makaron");
  await page.screenshot({ path: "test-results/profile-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator("body")).toHaveJSProperty("scrollWidth", 390);
  await page.screenshot({ path: "test-results/profile-mobile.png", fullPage: true });
  await page.getByRole("button", { name: "Usuń: Ulubione jedzenie", exact: true }).click();
  await expect(page.getByRole("textbox", { name: "Ulubione jedzenie", exact: true })).toHaveCount(0);
  await page.goto("/?new=1");
  await expect(page.getByRole("heading", { name: "Cześć, Alicja!", exact: true })).toBeVisible();
  await page.getByRole("link", { name: "Profil", exact: true }).click();
  await page.getByRole("button", { name: "Usuń: Imię", exact: true }).click();
  await expect(page.getByRole("textbox", { name: "Imię", exact: true })).toHaveValue("");
  await page.getByRole("textbox", { name: "Imię", exact: true }).fill("Anna");
  await page.getByRole("button", { name: "Zapisz: Imię", exact: true }).click();
  await expect(page.getByRole("status")).toHaveText("Zapisano zmianę.");
  page.once("dialog", dialog => dialog.dismiss());
  await page.getByRole("button", { name: "Wyczyść cały profil", exact: true }).click();
  await expect(page.getByRole("textbox", { name: "Imię", exact: true })).toHaveValue("Anna");
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "Wyczyść cały profil", exact: true }).click();
  await expect(page.getByRole("status")).toHaveText("Profil został wyczyszczony.");
  expect((await (await context.request.get("/api/profile")).json()).profile).toMatchObject({ name: null, preferences: {} });
  await page.goto("/?new=1");
  await expect(page.getByRole("heading", { name: "Cześć!", exact: true })).toBeVisible();
});
